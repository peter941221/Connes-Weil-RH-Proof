"""Generate exact-rational Lean proofs for the 2521 family fallback.

No floating-point arithmetic supplies a bound. The 2498 Taylor expression is
evaluated as Fractions, rounded upwards, and reproved by norm_num in Lean.
The final certificate covers both signs and every non-safe production cell.
The safe-cell table is retained as data with its analytic premise still open.
"""
import argparse
import hashlib
import json
import math
from fractions import Fraction as F
from pathlib import Path

import routea_owner_family_binding_2493 as binding

ROOT = Path(__file__).resolve().parents[1]
MODULE = ROOT / "ConnesWeilRH/Dev/C1RouteAFallbackCertificate2522.lean"
ARTIFACT = ROOT / "results/2522_fallback_certificate.json"


def ceil_grid(x, denominator):
    return F(-((-x.numerator * denominator) // x.denominator), denominator)


def lit(x):
    return f"(({x.numerator} : ℝ) / {x.denominator})"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def produce():
    scalar, coefs = binding.parse_lean_defs()
    lines = [
        "import ConnesWeilRH.Dev.C1RouteAFallbackScalar2522",
        "import Mathlib.Algebra.BigOperators.Fin",
        "",
        "/-! Generated by scripts/routea_fallback_certificate_2522.py.",
        "Every numeric upper below is proved in Lean; Python only chooses witnesses.",
        "Safe-cell table inequalities remain open. -/",
        "",
        "namespace ConnesWeilRH.Dev",
        "open ConnesWeilRH.Source.C1ScaledExpRationalEnvelope",
        "open ConnesWeilRH.Source.C1RouteAItem5Arithmetic",
        "set_option linter.style.longLine false",
        "set_option maxRecDepth 100000",
        "",
    ]
    rows = []
    bounds = []
    for i in range(30):
        radius = scalar[f"rad{i}_2460"]
        modulation = abs(scalar[f"mod{i}_2460"])
        coefficient = sum(map(abs, coefs[f"coef{i}_2460"]))
        z = 30 - radius / 2
        n = z.numerator // z.denominator
        remainder = z - n
        assert 0 <= remainder <= 1
        taylor = sum(((-remainder)**k / math.factorial(k) for k in range(20)), F(0))
        upper = F(3678794411714424, 10**16)**n * (
            taylor + F(21, math.factorial(20)*20))
        exp_upper = ceil_grid(upper, 10**28)
        factor = coefficient * (3720/radius**2 + 120*modulation/radius +
                                modulation**2 + 60/radius + modulation + F(1, 4))
        bound = ceil_grid(exp_upper * factor, 1024)
        assert upper <= exp_upper and exp_upper*factor <= bound
        bounds.append(bound)
        rows.append({"family": i, "integer_exponent": n,
                     "exp_upper": str(exp_upper), "family_upper": str(bound)})
        defs = (f"ownerRad_2463, ownerMod_2463, ownerCoef_2463, "
                f"rad{i}_2460, mod{i}_2460, coef{i}_2460")
        lines += [
            f"theorem fallbackFamily{i}_bound2522 (sigma : ℝ)",
            "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ)) :",
            f"    ownerFamilyWeightedCurvatureL1_2488 sigma {i} ≤ {lit(bound)} := by",
            f"  have he := exp_neg_nat_interval_upper2498 (30 - ownerRad_2463 {i} / 2) {n}",
            f"    (by norm_num [{defs}]) (by norm_num [{defs}])",
            f"  have hexp : Real.exp (ownerRad_2463 {i} / 2 - 30) ≤ {lit(exp_upper)} := by",
            "    calc",
            f"      Real.exp (ownerRad_2463 {i} / 2 - 30) =",
            f"          Real.exp (-(30 - ownerRad_2463 {i} / 2)) := by congr 1; ring",
            "      _ ≤ _ := he",
            f"      _ ≤ {lit(exp_upper)} := by",
            f"        norm_num [{defs}, expNegOneUpper2498, expTaylor20,",
            "          expTaylor20Error, Finset.sum_range_succ]",
            f"  rw [ownerFamilyFallback_scalar2522 sigma {i} hsigma]",
            "  calc",
            f"    _ ≤ {lit(exp_upper)} * familyFallbackFactor2522",
            f"        (ownerCoef_2463 {i}) (ownerMod_2463 {i}) (ownerRad_2463 {i}) := by",
            "      apply mul_le_mul_of_nonneg_right hexp",
            f"      norm_num [familyFallbackFactor2522, {defs}]",
            f"    _ ≤ {lit(bound)} := by norm_num [familyFallbackFactor2522, {defs}]",
            "",
        ]
    assert sum(bounds) <= 1387328
    lines += ["noncomputable def fallbackFamilyUpper2522 (i : Fin 30) : ℝ :=", "  match i.val with"]
    lines += [f"  | {i} => {lit(bound)}" for i, bound in enumerate(bounds)]
    lines += ["  | _ => 0", "",
              "theorem fallbackFamily_bound2522 (sigma : ℝ) (i : Fin 30)",
              "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ)) :",
              "    ownerFamilyWeightedCurvatureL1_2488 sigma i ≤ fallbackFamilyUpper2522 i := by",
              "  fin_cases i"]
    lines += [f"  · exact fallbackFamily{i}_bound2522 sigma hsigma" for i in range(30)]
    # Use the previously validated right-associated Fin sum expansion convention.
    chain = "f 29"
    for i in reversed(range(29)):
        chain = f"f {i} + ({chain})"
    lines += ["", "private theorem sum30_chain2522 (f : Fin 30 → ℝ) :",
              f"    (∑ i : Fin 30, f i) = {chain} := by",
              "  simp only [Fin.sum_univ_succ, Fin.sum_univ_zero, add_zero]",
              "  rfl", "",
              "theorem familyFallback_bound2522 (sigma : ℝ)",
              "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ)) :",
              "    ownerFamilyL1SumCurvature2488 sigma ≤ 1387328 := by",
              "  calc",
              "    _ ≤ ∑ i : Fin 30, fallbackFamilyUpper2522 i :=",
              "      Finset.sum_le_sum (fun i _ => fallbackFamily_bound2522 sigma i hsigma)",
              "    _ ≤ 1387328 := by",
              "      rw [sum30_chain2522]",
              "      norm_num [fallbackFamilyUpper2522]", "",
              "noncomputable def ownerProductionTable2522 (index : ℕ) : ℝ :=",
              "  if ownerProductionSafe2516 index = true then",
              "    (ownerProductionExpTable2519 (Fin.ofNat 640 index) : ℝ)",
              "  else 1387328", "",
              "theorem fallback_hcell2522 (sigma : ℝ) (index : ℕ)",
              "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ))",
              "    (hunsafe : ¬ (196 ≤ index ∧ index ≤ 443)) :",
              "    ownerProductionRemainderTerm2521 sigma index ≤ ownerProductionTable2522 index := by",
              "  simpa [ownerProductionRemainderTerm2521, ownerProductionTable2522,",
              "    ownerProductionSafe2516, hunsafe] using familyFallback_bound2522 sigma hsigma", "",
              "theorem cell0_hcell2522 (sigma : ℝ)",
              "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ)) :",
              "    ownerProductionRemainderTerm2521 sigma 0 ≤ ownerProductionTable2522 0 :=",
              "  fallback_hcell2522 sigma 0 hsigma (by omega)", "",
              "theorem ownerPanelStripNorm_le_safeTable2522 (sigma : ℝ)",
              "    (hsigma : sigma = -(1 / 2 : ℝ) ∨ sigma = (1 / 2 : ℝ))",
              "    (hsafe : ∀ index ∈ Finset.range 640, 196 ≤ index → index ≤ 443 →",
              "      ownerProductionRemainderTerm2521 sigma index ≤",
              "        (ownerProductionExpTable2519 (Fin.ofNat 640 index) : ℝ)) :",
              "    stripNorm sigma ownerPanelSumValue_2467 ≤",
              "      compositeNodeUpper2347",
              "        (ownerPanelNodeUpper2471 sigma stripRadius2303 (stripRadius2303 / 320))",
              "        (stripRadius2303 / 320) 640 +",
              "      localCurvatureRemainder2474 ownerProductionTable2522 (stripRadius2303 / 320) 640 := by",
              "  apply ownerPanelStripNorm_le_productionTable2521 sigma ownerProductionTable2522",
              "  intro index hi",
              "  by_cases hs : 196 ≤ index ∧ index ≤ 443",
              "  · simpa [ownerProductionTable2522, ownerProductionSafe2516, hs] using",
              "      hsafe index hi hs.1 hs.2",
              "  · exact fallback_hcell2522 sigma index hsigma hs", "",
              "end ConnesWeilRH.Dev", ""]
    return "\n".join(lines), rows, sum(bounds)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, rows, total = produce()
    if args.check:
        assert MODULE.read_text(encoding="utf-8") == source, "generated Lean module drift"
        artifact = json.loads(ARTIFACT.read_text(encoding="utf-8"))
        assert artifact["rows"] == rows
        assert artifact["module_sha256"] == sha(MODULE)
        for name, digest in artifact["sources"].items():
            assert sha(ROOT/name) == digest, f"source drift: {name}"
        print("PASS: exact witnesses, generated source, and source hashes")
        return
    MODULE.write_text(source, encoding="utf-8")
    paths = [Path(__file__).resolve(), binding.LEAN,
             ROOT/"ConnesWeilRH/Dev/C1RouteAFallbackScalar2522.lean",
             ROOT/"ConnesWeilRH/Dev/C1RouteAExpFamilyFallback2521.lean"]
    ARTIFACT.write_text(json.dumps({
        "record": 2522, "status": "EXACT_WITNESSES_BUILD_REQUIRED",
        "rows": rows, "sum_family_uppers_exact": str(total),
        "fallback_upper": 1387328, "fallback_cell_count": 392,
        "module_sha256": sha(MODULE),
        "sources": {str(p.relative_to(ROOT)).replace('\\', '/'): sha(p) for p in paths},
        "scope": "2463 fixed midpoint coefficients; both sigma signs; safe hcell still open",
    }, indent=2)+"\n", encoding="utf-8")
    print(f"Generated 30 family proofs; exact sum = {total}; upper = 1387328")


if __name__ == "__main__":
    main()
