"""Validate the external 2338-to-2570 membership handoff.

This binds the analytic repair artifact, the correction-box margin probe, and
 the generated Lean box source. It deliberately does not claim a Lean theorem.
"""
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPAIR = ROOT / "results/2338_exact_interpolation_repair.json"
MARGIN = ROOT / "results/2564_membership_margin_probe.json"
BOXES = ROOT / "ConnesWeilRH/Dev/C1RouteACorrectionCoefficientBoxes2570.lean"
CENTER = ROOT / "ConnesWeilRH/Dev/C1RouteACorrectionCenterNode2570.lean"


def upper(value):
    return Fraction(value["upper_exact"])


def main():
    repair = json.loads(REPAIR.read_text(encoding="utf-8"))
    margin = json.loads(MARGIN.read_text(encoding="utf-8"))
    repair_hash = hashlib.sha256(REPAIR.read_bytes()).hexdigest()
    assert repair["record"] == 2338
    assert repair["status"] == "EXACT_FINITE_NODE_REPAIR_ENCLOSED_ONLY"
    assert repair["matrix_dimension"] == 30
    assert repair["solve_algorithm"] == "precond"
    assert repair["solution_interval_residual_contains_zero"] is True
    assert upper(repair["neumann_defect_infinity_upper"]) < Fraction(1, 2)
    assert len(repair["coefficient_rows"]) == 30
    assert margin["record"] == 2564
    assert margin["source_sha256"] == repair_hash
    correction = margin["correction"]
    assert correction["slots_checked"] == 30
    assert correction["representatives_inside_boxes"] == 30
    assert correction["box_slack_ratio"] > 1.0
    assert correction["smallest_k_within_half_error"] <= 200
    box_text = BOXES.read_text(encoding="utf-8")
    center_text = CENTER.read_text(encoding="utf-8")
    assert f"Source SHA256: {repair_hash}" in box_text
    assert "Generated by scripts/generate_correction_pair_2570.py" in center_text
    assert "exact-owner membership is not asserted" in box_text
    assert "actual interpolation coefficients remains a consumer premise" in center_text
    result = {
        "record": 2581,
        "status": "EXTERNAL_MEMBERSHIP_HANDOFF_PASS",
        "scope": "2338 analytic repair to 2570 correction-box handoff",
        "matrix_dimension": repair["matrix_dimension"],
        "neumann_defect_lt_half": True,
        "solution_interval_residual_contains_zero": True,
        "correction_slots_checked": correction["slots_checked"],
        "correction_representatives_inside_boxes": correction["representatives_inside_boxes"],
        "correction_box_slack_ratio": correction["box_slack_ratio"],
        "correction_smallest_k_within_half_error": correction["smallest_k_within_half_error"],
        "repair_source_sha256": repair_hash,
        "margin_source_sha256": margin["source_sha256"],
        "box_source_sha256": hashlib.sha256(BOXES.read_bytes()).hexdigest(),
        "center_source_sha256": hashlib.sha256(CENTER.read_bytes()).hexdigest(),
        "lean_box_source_hash_bound": True,
        "lean_membership_theorem": False,
        "owner_transfer_to_live_consumer": False,
        "producer_go": False,
        "rh_claim": False,
    }
    output = ROOT / "results/2581_membership_handoff.json"
    output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2), flush=True)


if __name__ == "__main__":
    main()
