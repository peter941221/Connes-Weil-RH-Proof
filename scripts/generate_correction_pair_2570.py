def read_text(path):
    return path.read_text(encoding="utf-8")


def read_dev(name):
    return read_text(ROOT / f"ConnesWeilRH/Dev/{name}.lean")


def rename(source, old, record, new, target):
    return re.sub(r"\b" + old + r"(\w*)" + str(record) + r"\b",
                  lambda m: new + m[1] + str(target), source)


def derive_generator(path, substitutions):
    """2567 remainder law: token-substitute a generator source and exec it."""
    original = read_text(path)
    derived = original
    for old, new in substitutions:
        derived = derived.replace(old, new)
    tokens = [t for pair_ in substitutions for t in pair_]
    strip = re.compile("|".join(re.escape(t) for t in tokens))
    assert strip.sub("", original) == strip.sub("", derived), \
        f"remainder drift deriving {path.name}"
    namespace = {"__name__": "derived_generator", "__file__": str(path)}
    exec(compile(derived, str(path), "exec"), namespace)
    return namespace


