def chunked(value):
    """AGENTS 2bj chunked literal: 68-digit chunks, powers = sum of later widths.

    Powers accumulate the RAW digit-slice widths: int() strips leading zeros,
    so len(str(chunk)) would shrink the power of every earlier chunk whenever
    a later chunk starts with 0 (the 2568-era denominator incident).
    """
    num, den = value.numerator, value.denominator

    def parts(value):
        digits = str(abs(value))
        spans = []
        start = 0
        if len(digits) % 68:
            spans.append((0, len(digits) % 68))
            start = len(digits) % 68
        while start < len(digits):
            spans.append((start, start + 68))
            start += 68
        chunks = [(int(digits[a:b]), b - a) for a, b in spans]
        out, total = [], 0
        for chunk, width in reversed(chunks):
            out.append((chunk, total))
            total += width
        sign = "-" if value < 0 else ""
        terms = []
        for chunk, power in reversed(out):
            if chunk == 0 and len(out) > 1:
                continue
            if power:
                terms.append(f"({sign}{chunk} : ℝ) * 10^{power}")
            else:
                terms.append(f"({sign}{chunk} : ℝ)")
        return " +\n      ".join(terms)

    def read_back(text):
        return Q(eval(text.replace(": ℝ", "").replace("* 10^", "*10**")
                      .replace("\n", " ").replace(" ", "")))

    literal = f"({parts(num)}) /\n    ({parts(den)})"
    assert read_back(parts(num)) / read_back(parts(den)) == value, \
        "chunked literal round-trip drift"
    return literal


