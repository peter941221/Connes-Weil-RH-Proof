def integer(value, chunk=10 ** 60):
    high, low = divmod(abs(value), chunk)
    if not high:
        return str(value)
    sign, operation = ("-", "-") if value < 0 else ("", "+")
    return f"({sign}{high} * 10^60 {operation}\n            {low})"


def box_rows(key):
    rows = json.loads(read_text(
        ROOT / "results/2338_exact_interpolation_repair.json"))["coefficient_rows"]
    assert len(rows) == 30
    out = []
    for index, row in enumerate(rows):
        assert row["index"] == index
        values = []
        for component in ("real", "imag"):
            lo, hi = (Q(row[key][component][side])
                      for side in ("lower_exact", "upper_exact"))
            assert lo <= hi
            values.extend((lo, hi))
        out.append(values)
    return out


