#!/usr/bin/env python3
"""Emit the Lean table module for the extracted CC20 equation-(115) data.

Consumes the validated manifest produced by extract_source.py and emits a
deterministic Lean data module.  The emitted table stores each published
angle and coefficient as an exact rational numerator/denominator pair; no
floating-point value enters the Lean file.

The output is a pure function of the manifest bytes: same manifest, same
file.  The generator performs no arithmetic beyond copying validated
integers, so it introduces no numerical claims of its own.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from fractions import Fraction
from pathlib import Path

M = 1732


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def load_manifest(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as stream:
        manifest = json.load(stream)
    if manifest.get("schema_version") != 1:
        raise ValueError("manifest schema_version is not 1")
    if manifest.get("m") != M:
        raise ValueError(f"manifest m is {manifest.get('m')!r}, expected {M}")
    if len(manifest.get("angles", [])) != M:
        raise ValueError(f"manifest angles does not have {M} entries")
    if len(manifest.get("coefficients", [])) != M:
        raise ValueError(f"manifest coefficients does not have {M} entries")
    return manifest


def entry_fraction(entry: dict) -> Fraction:
    value = Fraction(int(entry["numerator"]), int(entry["denominator"]))
    return value


def lean_ℚ_literal(numerator: int, denominator: int) -> str:
    if denominator <= 0:
        raise ValueError("nonpositive denominator in manifest entry")
    return f"({numerator} : ℚ) / {denominator}"


def emit_table_module(manifest: dict, manifest_sha256: str) -> str:
    angles = [entry_fraction(e) for e in manifest["angles"]]
    coefficients = [entry_fraction(e) for e in manifest["coefficients"]]

    for index, value in enumerate(angles, start=1):
        if value <= 0:
            raise ValueError(
                f"angle entry {index} is {value}, expected positive; the "
                "paired-sign table construction requires the published half "
                "to be positive"
            )

    angle_docs = manifest["angles"]
    coeff_docs = manifest["coefficients"]
    angles_sha = angle_docs[0]["source"].split("sha256=")[1].split(";")[0]
    coeffs_sha = coeff_docs[0]["source"].split("sha256=")[1].split(";")[0]
    angles_url = angle_docs[0]["source"].split("url=")[1].split(";")[0]
    coeffs_url = coeff_docs[0]["source"].split("url=")[1].split(";")[0]

    lines: list[str] = []
    lines.append("/-")
    lines.append("Copyright (c) 2026 ConnesWeilRH contributors. All rights reserved.")
    lines.append("Released under Apache 2.0 license as described in the file LICENSE.")
    lines.append("-/")
    lines.append("")
    lines.append("import ConnesWeilRH.Dev.C1CC20FiniteRankApproximation")
    lines.append("")
    lines.append("/-!")
    lines.append("# The extracted CC20 equation-(115) table")
    lines.append("")
    lines.append("The published CC20 angle and coefficient tables behind equations")
    lines.append("(114)--(115), stored as exact rationals with their provenance chain:")
    lines.append("")
    lines.append(f"* angles: {angles_url}")
    lines.append(f"  sha256 = `{angles_sha}`")
    lines.append(f"* coefficients: {coeffs_url}")
    lines.append(f"  sha256 = `{coeffs_sha}`")
    lines.append(f"* manifest sha256 = `{manifest_sha256}`")
    lines.append("")
    lines.append("This file is generated by `scripts/cc20_eq115/gen_eq115_table.py`")
    lines.append("from `scripts/cc20_eq115/data/cc20_eq115_manifest.json` (itself the")
    lines.append("deterministic output of `extract_source.py` on the two published DOCX")
    lines.append("inputs).  Regenerate rather than hand-edit; every integer here is a")
    lines.append("copied manifest entry, and no floating-point value enters this file.")
    lines.append("")
    lines.append("The published tables list the positive half `n = 1..m`; the full")
    lines.append("equation-(114) data set also contains the central `n = 0` term with")
    lines.append("`d(0) = 0`.  It is realized structurally in `cc20Eq115Data` over")
    lines.append("`Option (Fin m × Bool)`: `none` is zero and `some` carries the paired")
    lines.append("nonzero signs.  No digit-level pairing check is ever needed.")
    lines.append("-/")
    lines.append("")
    lines.append("namespace ConnesWeilRH")
    lines.append("")
    lines.append("namespace Source")
    lines.append("")
    lines.append("namespace C1CC20Eq115Table")
    lines.append("")
    lines.append("open C1CC20FiniteRankApproximation")
    lines.append("")

    def emit_ite_table(name: str, doc_lines: list[str], values: list[Fraction]) -> None:
        """Emit the table as a nested if-then-else chain on `n.val`.

        A literal-per-branch `match` makes the Fin splitter burn heartbeats at
        `whnf`; a deep ite chain elaborates in linear time and is never
        evaluated by the proofs, which only touch the sign slot.
        """
        lines.append("-- The generated table is a very deep ite chain; the default")
        lines.append("-- elaborator budgets are sized for hand-written proofs.")
        lines.append("set_option maxHeartbeats 1000000 in")
        lines.append("set_option maxRecDepth 100000 in")
        for doc_line in doc_lines:
            lines.append(doc_line)
        lines.append(f"def {name} : Fin 1732 → ℚ := fun n =>")
        for index, value in enumerate(values[:-1]):
            lines.append(
                f"  if n.val = {index} then "
                f"{lean_ℚ_literal(value.numerator, value.denominator)} else"
            )
        tail = values[-1]
        lines.append(f"  {lean_ℚ_literal(tail.numerator, tail.denominator)}")
        lines.append("")

    emit_ite_table(
        "cc20Eq115AngleQ",
        [
            "/-- The exact rational value of the published angle `alpha_n`,",
            "`n = 1..m`.  This is the positive half; `cc20Eq115Data` attaches the",
            "signs. -/",
        ],
        angles,
    )
    emit_ite_table(
        "cc20Eq115CoefficientQ",
        [
            "/-- The exact rational value of the published coefficient `d_n`,",
            "`n = 1..m`. -/",
        ],
        coefficients,
    )
    lines.append("")
    lines.append("/-- The published angle `alpha_n` as a real number. -/")
    lines.append("noncomputable def cc20Eq115Angle (n : Fin 1732) : Real := cc20Eq115AngleQ n")
    lines.append("")
    lines.append("/-- The published coefficient `d_n` as a real number. -/")
    lines.append("noncomputable def cc20Eq115Coefficient (n : Fin 1732) : Real :=")
    lines.append("  cc20Eq115CoefficientQ n")
    lines.append("")
    lines.append("/-- The nonzero equation-(114) table over the paired index `Fin m × Bool`.")
    lines.append("This is retained as the exact table payload; the paper's operator also")
    lines.append("contains the separate central term `n = 0`. -/")
    lines.append("noncomputable def cc20Eq115NonzeroData (lam : Real) :")
    lines.append("    CC20FiniteRankData (Fin 1732 × Bool) where")
    lines.append("  lambda := lam")
    lines.append("  frequency := fun i =>")
    lines.append("    if i.2 then ((i.1 : Nat) : Real) + 1 else -(((i.1 : Nat) : Real) + 1)")
    lines.append("  perturbedFrequency := fun i =>")
    lines.append("    if i.2 then cc20Eq115Angle i.1 else -(cc20Eq115Angle i.1)")
    lines.append("  coefficient := fun i => cc20Eq115Coefficient i.1")
    lines.append("")
    lines.append("/-- The full equation-(114)/(119) finite data set.  `none` is the")
    lines.append("central index `n = 0`, where `alpha_0 = 0` and `d(0) = 0`; hence its")
    lines.append("operator term is exactly `e_0`.  At `some i`, the `Bool` slot carries")
    lines.append("the sign, so `frequency` and `perturbedFrequency` flip while")
    lines.append("`coefficient` is sign-independent, matching the paper's conventions")
    lines.append("`alpha_{-n} = -alpha_n` and `d(-n) = d(n)`.  The scale `lambda` stays a")
    lines.append("parameter: the published tables fix the angles and coefficients, not")
    lines.append("the strict `lambda` interval, which remains an open certificate side.")
    lines.append("-/")
    lines.append("noncomputable def cc20Eq115Data (lam : Real) :")
    lines.append("    CC20FiniteRankData (Option (Fin 1732 × Bool)) where")
    lines.append("  lambda := lam")
    lines.append("  frequency")
    lines.append("    | none => 0")
    lines.append("    | some i => (cc20Eq115NonzeroData lam).frequency i")
    lines.append("  perturbedFrequency")
    lines.append("    | none => 0")
    lines.append("    | some i => (cc20Eq115NonzeroData lam).perturbedFrequency i")
    lines.append("  coefficient")
    lines.append("    | none => 0")
    lines.append("    | some i => (cc20Eq115NonzeroData lam).coefficient i")
    lines.append("")
    lines.append("/-- The sign-flip involution fixing the central index. -/")
    lines.append("def cc20Eq115NegIndex :")
    lines.append("    Option (Fin 1732 × Bool) ≃ Option (Fin 1732 × Bool) where")
    lines.append("  toFun")
    lines.append("    | none => none")
    lines.append("    | some i => some (i.1, !i.2)")
    lines.append("  invFun")
    lines.append("    | none => none")
    lines.append("    | some i => some (i.1, !i.2)")
    lines.append("  left_inv i := by rcases i with _ | ⟨n, s⟩ <;> simp")
    lines.append("  right_inv i := by rcases i with _ | ⟨n, s⟩ <;> simp")
    lines.append("")
    lines.append("end C1CC20Eq115Table")
    lines.append("")
    lines.append("end Source")
    lines.append("")
    lines.append("end ConnesWeilRH")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("scripts/cc20_eq115/data/cc20_eq115_manifest.json"),
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("ConnesWeilRH/Dev/C1CC20Eq115Table.lean"),
    )
    args = parser.parse_args()

    manifest_bytes = args.manifest.read_bytes()
    manifest_sha256 = hashlib.sha256(manifest_bytes).hexdigest()
    manifest = load_manifest(args.manifest)

    module = emit_table_module(manifest, manifest_sha256)
    args.out.write_text(module, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(module)} chars), sha256={sha256_text(module)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
