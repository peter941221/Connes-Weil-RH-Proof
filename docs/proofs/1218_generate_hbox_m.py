"""1218 - emit ConnesWeilRH/Dev/C1HboxRationalDataQ28M.lean: the M-side
fork of the committed record-1119 Hbox data (prereg 1218 section 3).

Emits only the M-dependent slice: radM_q28M, Lam_q28M, absLam_q28M,
DredRad_q28M + hsymRadM / hrevM / habsLam / hLamL / hLLam / hDredRad /
hRadp.  The reverse containment hrevM ties Q28M.M +- radM_q28M to the
COMMITTED record-1217 Lean boxes C1GateMatrixBoxData.MLo_q28M/MHi_q28M.
G-side data (radG_q28, GLo_q28, GHi_q28, absK_q28, hrevG_q28,
hsymRadG_q28, habsK_q28) is reused from C1HboxRationalData by import.

Falsifier F5: every emitted identity is asserted over exact Fractions
at generation time -> mismatch = exit 1, nothing emitted.  RH NOT
claimed.
"""
import json
import os
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
QCHAIN = os.path.join(HERE, "1218_qchain_q28.json")
BUNDLE = os.path.join(HERE, "1218_cert_q28.json")
OUT = os.path.join(HERE, "..", "..", "ConnesWeilRH", "Dev",
                   "C1HboxRationalDataQ28M.lean")


def fr(x):
    return F(x)


def mm(A, B):
    n, k, m = len(A), len(B), len(B[0])
    return [[sum(A[i][t] * B[t][j] for t in range(k)) for j in range(m)]
            for i in range(n)]


def mt(A):
    return [list(r) for r in zip(*A)]


def lit(s):
    return f"({s} : ℝ)"


def rows_str(rows, ind):
    pad = " " * ind
    return ";\n".join(pad + ", ".join(lit(x) for x in r) for r in rows)


def matdef(name, n, m, rows):
    return (f"noncomputable def {name} : Matrix (Fin {n}) (Fin {m}) ℝ :=\n"
            f"  !![\n{rows_str(rows, 4)}\n  ]\n")


qc = json.load(open(QCHAIN))["classes"][0]
ce = json.load(open(BUNDLE))["classes"][0]
assert qc["A_R"] == 2.0 and ce["A_R"] == 2.0
U = fr(qc["U"])
mu = -U
assert mu == abs(U)
mid_M = [[fr(x) for x in r] for r in qc["mid_M"]]
rad_M = [[fr(x) for x in r] for r in qc["rad_M"]]
K = [[fr(x) for x in r] for r in qc["K"]]
Lam = [[fr(x) for x in r] for r in qc["Lam"]]
Lw = [[fr(x) for x in r] for r in qc["Ldl_L"]]
DredRad = [[fr(x) for x in r] for r in qc["Dred_rad"]]
radp = [[fr(x) for x in r] for r in qc["radp"]]
radG = [[fr(x) for x in r] for r in qc["rad_G"]]
M_lo = [[fr(x) for x in r] for r in ce["M_lo"]]
M_hi = [[fr(x) for x in r] for r in ce["M_hi"]]

# ---- F5 asserts ----
ok = True
for i in range(8):
    for j in range(8):
        # reverse containment: bundle box inside radius box (exact here)
        if not (mid_M[i][j] - rad_M[i][j] <= M_lo[i][j]
                and M_hi[i][j] <= mid_M[i][j] + rad_M[i][j]):
            ok = False
assert ok, "reverse containment M failed"
assert all(Lam[i][i] == 1 for i in range(5)), "Lam not unit diagonal"
assert all(Lam[i][j] == 0 for i in range(5) for j in range(i + 1, 5)), \
    "Lam not unit lower"
assert mm(Lam, Lw) == [[F(1) if i == j else F(0) for j in range(5)]
                       for i in range(5)], "Lam * L != I"
assert mm(Lw, Lam) == [[F(1) if i == j else F(0) for j in range(5)]
                       for i in range(5)], "L * Lam != I"
aK = [[abs(x) for x in r] for r in K]
aL = [[abs(x) for x in r] for r in Lam]
p = [[mu * radG[i][j] + rad_M[i][j] for j in range(8)] for i in range(8)]
DR = mm(mm(mt(aK), p), aK)
assert DR == DredRad, "|K|^T (mu radG + radM) |K| != DredRad"
RP = mm(mm(aL, DredRad), mt(aL))
assert RP == radp, "|Lam| DredRad |Lam|^T != radp"
print("F5 PASS: reverse containment M + Lam inverse + DredRad + radp")

