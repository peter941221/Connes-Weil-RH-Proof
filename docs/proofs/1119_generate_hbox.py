#!/usr/bin/env python3
"""Record 1119 generator: emit ConnesWeilRH/Dev/C1HboxRationalData.lean.

Inputs (the ONLY inputs, both committed):
  - docs/proofs/1115_qchain.json  (mid/rad, K, Ldl_L, Lam, Dred_rad, radp)
  - docs/proofs/1112_cert.json, docs/proofs/1113_cert.json (G_lo/G_hi/M_lo/M_hi)

Every identity that the emitted Lean file proves by `norm_num` is FIRST
asserted here over exact Fractions (falsifier discipline, preregistration
section 3): if any check fails, nothing is emitted and the script exits 1.

Checks per class:
  0. U equals the committed Q*.lean literal.
  1. rad_G / rad_M exactly symmetric.
  2. REVERSE containment (bundle box inside the 1115 box):
     mid - rad <= lo  and  hi <= mid + rad  (entrywise, G and M).
  3. Lam unit-lower-triangular; Lam * Ldl_L = Ldl_L * Lam = I.
  4. |K|^T (mu radG + radM) |K| = Dred_rad   (mu = -U = |U|).
  5. |Lam| Dred_rad |Lam|^T = radp  (ties to the LANDED record-1118 data).
"""
import json
import os
import re
import sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEV = os.path.join(ROOT, "ConnesWeilRH", "Dev")


def F(s):
    return Fraction(s)


def fr_list(x):
    return [[F(v) for v in row] for row in x]


def mat_mul(A, B):
    n, m, p = len(A), len(B), len(B[0])
    return [[sum(A[i][t] * B[t][j] for t in range(m)) for j in range(p)]
            for i in range(n)]


def mat_T(A):
    return [list(r) for r in zip(*A)]


def mat_abs(A):
    return [[abs(v) for v in row] for row in A]


def mat_add(A, B):
    return [[a + b for a, b in zip(ra, rb)] for ra, rb in zip(A, B)]


def mat_scal(c, A):
    return [[c * v for v in row] for row in A]


def ident(n):
    return [[F(1) if i == j else F(0) for j in range(n)] for i in range(n)]


def lit(s):
    return f"({s} : ℝ)"


def matdef(name, typ, rows):
    lines = [f"noncomputable def {name} : {typ} :=", "  !!["]
    for r, row in enumerate(rows):
        sep = ";" if r < len(rows) - 1 else ""
        lines.append("    " + ", ".join(lit(v) for v in row) + sep)
    lines.append("  ]")
    return "\n".join(lines)


def committed_u(path):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r"noncomputable def U : ℝ := \((-?\d+)/(\d+) : ℝ\)", txt)
    if not m:
        raise SystemExit(f"U literal not found in {path}")
    return f"{m.group(1)}/{m.group(2)}"


qchain = json.load(open(os.path.join(HERE, "1115_qchain.json")))["classes"]
certs = (json.load(open(os.path.join(HERE, "1112_cert.json")))["classes"]
         + json.load(open(os.path.join(HERE, "1113_cert.json")))["classes"])

CLASSES = [
    ("q28", 2.0, "Q28", "1112_cert.json"),
    ("q38", 3.0, "Q38", "1113_cert.json"),
    ("q48", 4.0, "Q48", "1112_cert.json"),
]

ok_all = True


def check(name, ok, detail=""):
    global ok_all
    ok_all = ok_all and ok
    print(("PASS " if ok else "FAIL ") + name + (("  " + detail) if detail else ""))
    return ok


HEADER = r"""/-
Copyright (c) 2026 ConnesWeilRH contributors. All rights reserved.
Released under the Apache 2.0 license as described in the file LICENSE.
-/

import ConnesWeilRH.Dev.C1WindowRationalIngestQ28
import ConnesWeilRH.Dev.C1WindowRationalIngestQ38
import ConnesWeilRH.Dev.C1WindowRationalIngestQ48
import ConnesWeilRH.Dev.C1GateLevelTransferClasses

/-!
# Record 1119: Hbox rational data (outward boxes + entrywise identities)

GENERATED by docs/proofs/1119_generate_hbox.py from docs/proofs/
1115_qchain.json + the certificate bundles 1112_cert.json / 1113_cert.json
(do not edit by hand - regenerate).  Lands sub-obligation (b)'s Lean half
of record 1118 (docs/proofs/1119_hbox_tbox_pullthrough_preregistration.md
section 1a):

- per class: the committed outward boxes `GLo/GHi/MLo/MHi` as exact
  rational data, the radius matrices `radG/radM`, and the REVERSE
  containment `[GLo, GHi] <= [G - radG, G + radG]` entrywise (the bridge
  from the named hypothesis `Hbox` to the radius form of the T-box
  statement);
- abs bridges for `K` and `Lam`;
- the provenance identities `hLamL`/`hLLam` (`Lam` is the two-sided
  inverse of the committed LDL factor `L`), `hDredRad`
  (`|K|^T (mu radG + radM) |K| = DredRad`), and `hRadp`
  (`|Lam| DredRad |Lam|^T = radp`, tying the new data to the LANDED
  record-1118 `radp`/`dd`/slacks, which are untouched).

Every theorem is an entrywise `norm_num` identity; the generation-time
script asserted each one over exact Fractions before emitting this file.
RH NOT claimed.
-/

namespace ConnesWeilRH
namespace Source
namespace C1HboxRationalData

open Matrix
open C1WindowRationalIngest
open C1GateLevelTransferClasses

-- Generated exact-rational data lines carry ~10^3-digit numerals and cannot
-- fit 100 columns (house convention for machine-generated data modules).
set_option linter.style.longLine false

/-- The outward-box predicate: the true data lies entrywise inside the
committed bundle boxes.  This is the named analytic hypothesis `Hbox` -
after the record-1119 pull-through, the entire (a)+(b) chain of the
class certificates reduces to it (plus the representation/normalization
slots), and nothing in this development trusts any float object. -/
def Hbox (GLo GHi MLo MHi : Matrix (Fin 8) (Fin 8) ℝ)
    (G_true M_true : Matrix (Fin 8) (Fin 8) ℝ) : Prop :=
  (∀ i j, GLo i j ≤ G_true i j ∧ G_true i j ≤ GHi i j) ∧
    (∀ i j, MLo i j ≤ M_true i j ∧ M_true i j ≤ MHi i j)

"""


def build_section(tag, label, src, qmod, qc, ce):
    rad_G = fr_list(qc["rad_G"])
    K = fr_list(qc["K"])
    Lam = fr_list(qc["Lam"])
    aK = [[str(v) for v in row] for row in mat_abs(K)]
    aL = [[str(v) for v in row] for row in mat_abs(Lam)]
    out = []
    out.append(f"section  -- class ({label}), source bundle {src}\n")
    out.append(f"-- Reverse containment (falsifier, asserted at generation):")
    worst_g = min(min(F(qc["mid_G"][i][j]) - rad_G[i][j] - F(ce["G_lo"][i][j]),
                      F(ce["G_hi"][i][j]) - F(qc["mid_G"][i][j]) - rad_G[i][j])
                  for i in range(8) for j in range(8))
    worst_m = min(min(F(qc["mid_M"][i][j]) - rad_M[i][j] - F(ce["M_lo"][i][j]),
                      F(ce["M_hi"][i][j]) - F(qc["mid_M"][i][j]) - rad_M[i][j])
                  for i in range(8) for j in range(8))
    out.append(f"-- worst G clearance = {float(worst_g):.6e}, worst M clearance = {float(worst_m):.6e}\n")
    out.append(matdef(f"radG_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", qc["rad_G"]))
    out.append("")
    out.append(matdef(f"radM_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", qc["rad_M"]))
    out.append("")
    out.append(matdef(f"GLo_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", ce["G_lo"]))
    out.append("")
    out.append(matdef(f"GHi_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", ce["G_hi"]))
    out.append("")
    out.append(matdef(f"MLo_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", ce["M_lo"]))
    out.append("")
    out.append(matdef(f"MHi_{tag}", "Matrix (Fin 8) (Fin 8) ℝ", ce["M_hi"]))
    out.append("")
    out.append(matdef(f"absK_{tag}", "Matrix (Fin 8) (Fin 5) ℝ", aK))
    out.append("")
    out.append(matdef(f"Lam_{tag}", "Matrix (Fin 5) (Fin 5) ℝ", qc["Lam"]))
    out.append("")
    out.append(matdef(f"absLam_{tag}", "Matrix (Fin 5) (Fin 5) ℝ", aL))
    out.append("")
    out.append(matdef(f"DredRad_{tag}", "Matrix (Fin 5) (Fin 5) ℝ", qc["Dred_rad"]))
    out.append("")
    out.append(f"""theorem hsymRadG_{tag} : ∀ i j, radG_{tag} i j = radG_{tag} j i := by
  intro i j
  fin_cases i <;> fin_cases j <;> simp [radG_{tag}]

theorem hsymRadM_{tag} : ∀ i j, radM_{tag} i j = radM_{tag} j i := by
  intro i j
  fin_cases i <;> fin_cases j <;> simp [radM_{tag}]

set_option maxHeartbeats 2000000000 in
-- reason: 64 entrywise conjunctions over 4-6-term rational sums
/-- REVERSE containment: the committed bundle box sits INSIDE the 1115
radius box, so `Hbox` implies `|G_true - G| <= radG` entrywise. -/
theorem hrevG_{tag} : ∀ i j, {qmod}.G i j - radG_{tag} i j ≤ GLo_{tag} i j ∧
    GHi_{tag} i j ≤ {qmod}.G i j + radG_{tag} i j := by
  intro i j
  fin_cases i <;> fin_cases j
  all_goals (simp [radG_{tag}, GLo_{tag}, GHi_{tag}, {qmod}.G] <;> norm_num)

set_option maxHeartbeats 2000000000 in
-- reason: 64 entrywise conjunctions over 4-6-term rational sums
theorem hrevM_{tag} : ∀ i j, {qmod}.M i j - radM_{tag} i j ≤ MLo_{tag} i j ∧
    MHi_{tag} i j ≤ {qmod}.M i j + radM_{tag} i j := by
  intro i j
  fin_cases i <;> fin_cases j
  all_goals (simp [radM_{tag}, MLo_{tag}, MHi_{tag}, {qmod}.M] <;> norm_num)

theorem habsK_{tag} : ∀ i j, absK_{tag} i j = |{qmod}.K i j| := by
  intro i j
  fin_cases i <;> fin_cases j <;> simp [absK_{tag}, {qmod}.K] <;> norm_num

theorem habsLam_{tag} : ∀ i j, absLam_{tag} i j = |Lam_{tag} i j| := by
  intro i j
  fin_cases i <;> fin_cases j <;> simp [absLam_{tag}, Lam_{tag}] <;> norm_num
""")
    out.append(f"""set_option maxHeartbeats 2000000000 in
-- reason: 25 entries x 5-term products of ~10^3-digit rationals
theorem hLamL_{tag} : Lam_{tag} * {qmod}.L = 1 := by
  ext i j
  fin_cases i <;> fin_cases j
  all_goals (simp [Lam_{tag}, {qmod}.L, Matrix.mul_apply,
    Fin.sum_univ_succ] <;> norm_num)

set_option maxHeartbeats 2000000000 in
-- reason: 25 entries x 5-term products of ~10^3-digit rationals
theorem hLLam_{tag} : {qmod}.L * Lam_{tag} = 1 := by
  ext i j
  fin_cases i <;> fin_cases j
  all_goals (simp [Lam_{tag}, {qmod}.L, Matrix.mul_apply,
    Fin.sum_univ_succ] <;> norm_num)

set_option maxHeartbeats 2000000000 in
-- reason: 25 entries x 64-term sums of ~10^2-digit products
theorem hDredRad_{tag} :
    Matrix.transpose absK_{tag} * (mu_{tag} • radG_{tag} + radM_{tag}) * absK_{tag}
      = DredRad_{tag} := by
  ext i j
  fin_cases i <;> fin_cases j
  all_goals (simp [absK_{tag}, radG_{tag}, radM_{tag}, mu_{tag}, {qmod}.U,
    DredRad_{tag}, Matrix.mul_apply, Matrix.transpose_apply,
    Fin.sum_univ_succ] <;> norm_num)

set_option maxHeartbeats 2000000000 in
-- reason: 25 entries x 125-term products of ~10^3-digit rationals
theorem hRadp_{tag} :
    absLam_{tag} * DredRad_{tag} * Matrix.transpose absLam_{tag} = radp_{tag} := by
  ext i j
  fin_cases i <;> fin_cases j
  all_goals (simp [absLam_{tag}, DredRad_{tag}, radp_{tag}, Matrix.mul_apply,
    Matrix.transpose_apply, Fin.sum_univ_succ] <;> norm_num)

end
""")
    return "\n".join(out)


sections = []
for tag, ar, qmod, src in CLASSES:
    qc = next(c for c in qchain if c["A_R"] == ar)
    ce = next(c for c in certs if c["A_R"] == ar)
    label = {2.0: "2,8", 3.0: "3,8", 4.0: "4,8"}[ar]
    U = F(qc["U"])
    mu = -U
    rad_G = fr_list(qc["rad_G"])
    rad_M = fr_list(qc["rad_M"])
    G_lo, G_hi = fr_list(ce["G_lo"]), fr_list(ce["G_hi"])
    M_lo, M_hi = fr_list(ce["M_lo"]), fr_list(ce["M_hi"])
    K, Lam = fr_list(qc["K"]), fr_list(qc["Lam"])
    DredRad, radp = fr_list(qc["Dred_rad"]), fr_list(qc["radp"])
    Lw = fr_list(qc["Ldl_L"])

    cu = committed_u(os.path.join(DEV, f"C1WindowRationalIngest{qmod}.lean"))
    check(f"[{tag}] U matches committed literal", U == F(cu), cu)
    check(f"[{tag}] rad_G symmetric",
          all(rad_G[i][j] == rad_G[j][i] for i in range(8) for j in range(8)))
    check(f"[{tag}] rad_M symmetric",
          all(rad_M[i][j] == rad_M[j][i] for i in range(8) for j in range(8)))
    check(f"[{tag}] reverse containment G",
          all(F(qc["mid_G"][i][j]) - rad_G[i][j] <= G_lo[i][j]
              and G_hi[i][j] <= F(qc["mid_G"][i][j]) + rad_G[i][j]
              for i in range(8) for j in range(8)))
    check(f"[{tag}] reverse containment M",
          all(F(qc["mid_M"][i][j]) - rad_M[i][j] <= M_lo[i][j]
              and M_hi[i][j] <= F(qc["mid_M"][i][j]) + rad_M[i][j]
              for i in range(8) for j in range(8)))
    check(f"[{tag}] Lam unit-lower",
          all(Lam[i][i] == 1 for i in range(5))
          and all(Lam[i][j] == 0 for i in range(5) for j in range(i + 1, 5)))
    check(f"[{tag}] Lam * Ldl_L = I", mat_mul(Lam, Lw) == ident(5))
    check(f"[{tag}] Ldl_L * Lam = I", mat_mul(Lw, Lam) == ident(5))
    p = mat_add(mat_scal(mu, rad_G), rad_M)
    DR = mat_mul(mat_mul(mat_T(mat_abs(K)), p), mat_abs(K))
    check(f"[{tag}] |K|^T (mu radG + radM) |K| = Dred_rad", DR == DredRad)
    RP = mat_mul(mat_mul(mat_abs(Lam), DredRad), mat_T(mat_abs(Lam)))
    check(f"[{tag}] |Lam| Dred_rad |Lam|^T = radp", RP == radp)

    sections.append(build_section(tag, label, src, qmod, qc, ce))

if not ok_all:
    print("\nFALSIFIER FIRED - no Lean emitted.")
    sys.exit(1)

body = HEADER + "\n\n".join(sections) + "\nend C1HboxRationalData\nend Source\nend ConnesWeilRH\n"

out_path = os.path.join(DEV, "C1HboxRationalData.lean")
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(body)
print(f"\nwrote {out_path} ({len(body)} bytes); all generation checks PASS")
